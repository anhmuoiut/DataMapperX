def write_rawdata_logs(root: Path) -> None:
    """Three serial numbers in folders whose path order differs from the serial-number order."""
    layout = {("aa", "VSE000125"): "125", ("bb", "VSE000123"): "123", ("cc", "VSE000124"): "124"}
    for (folder, sn), tag in layout.items():
        (root / folder).mkdir(parents=True)
        for run in (1, 2):
            blocks = [ict_block("R1", f"+{tag}.{run}0E+00", "+9.0E+02", "+0.0E+00"),
                      ict_block("Iin @ No  Load", f"+{run}.5E-03", "+1.0E-02", "-1.0E-02", kind="CAP"),
                      ict_block("Long", "+1.2345678901234567E+00" if run == 1 else "+1.2345678901234567E-03", kind="RES")]
            if sn == "VSE000124" and run == 2:
                blocks.pop(1)  # one file lacks a component
            write_ict_log(root / folder / f"f{run}.log", sn, blocks)


