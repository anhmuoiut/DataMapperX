def _obs(item, sample, value, low=None, high=None, **extra) -> Observation:
    return Observation(item, sample, value, low, high, **extra)


def _repeated(values=((1, 2, 3), (4, 5, 6), (7, 8, 9)), low=0, high=20, item="X", **extra):
    return [_obs(item, f"S{i}", value, low, high, trial=str(j), **extra)
            for i, group in enumerate(values) for j, value in enumerate(group)]


def _crossed(data, low=0, high=20, item="X", **extra):
    return [_obs(item, sample, value, low, high, trial=str(trial), operator=operator, **extra)
            for operator, samples in data.items() for sample, values in samples.items()
            for trial, value in enumerate(values, 1)]


def _capability(values=(1, 2, 3, 4, 5), low=0, high=6, item="X", **extra):
    return [_obs(item, f"S{i}", value, low, high, **extra) for i, value in enumerate(values)]


SAMPLES_A = {"S1": (1, 3), "S2": (4, 6), "S3": (7, 9)}


def _seeded_grr(rng, parts=10, trials=3, item="Seeded GRR"):
    effects = [rng.gauss(0, 1.0) for _ in range(parts)]
    return [_obs(item, f"P{p + 1}", 10 + effects[p] + rng.gauss(0, 0.1), 5, 15, trial=str(t + 1))
            for p in range(parts) for t in range(trials)]


def _seeded_crossed(rng, parts=10, trials=3, item="Seeded crossed"):
    effects = [rng.gauss(0, 1.0) for _ in range(parts)]
    bias = {"A": 0.0, "B": 0.45, "C": -0.45}
    return [_obs(item, f"P{p + 1}", 10 + effects[p] + bias[o] + rng.gauss(0, 0.1) + rng.gauss(0, 0.15), 5, 15,
                 trial=str(t + 1), operator=o)
            for o in bias for p in range(parts) for t in range(trials)]


